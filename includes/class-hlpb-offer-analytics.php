		echo '<input type="hidden" name="from" value="' . esc_attr( $filters['from'] ) . '"><input type="hidden" name="to" value="' . esc_attr( $filters['to'] ) . '"><input type="hidden" name="landing_id" value="' . esc_attr( $filters['landing_id'] ) . '"><input type="hidden" name="coupon_id" value="' . esc_attr( $filters['coupon_id'] ) . '"><input type="hidden" name="product_id" value="' . esc_attr( $filters['product_id'] ) . '"><input type="hidden" name="mode" value="' . esc_attr( $filters['mode'] ) . '">';
		foreach ( $filters['statuses'] as $status ) {
			echo '<input type="hidden" name="statuses[]" value="' . esc_attr( $status ) . '">';
		}
		echo '<button type="submit" class="button button-primary">' . esc_html__( 'Download detailed CSV', 'html-landing-page-builder-for-woocommerce' ) . '</button></form>';
	}

	/** Write one formula-safe CSV record. */
	private static function write_csv_row( $output, $values ) {
		$values = array_map(
			static function ( $value ) {
				if ( ! is_string( $value ) ) {
					return $value;
				}
				return preg_match( '/^\s*[=+@-]/', $value ) ? "'" . $value : $value;
			},
			$values
		);
		fputcsv( $output, $values );
	}

	private static function money( $amount, $currency ) {
		return wp_kses_post( wc_price( (float) $amount, array( 'currency' => $currency ) ) );
	}

	private static function mode_label( $mode ) {
		$labels = array(
			'buy'    => __( 'Buy More', 'html-landing-page-builder-for-woocommerce' ),
			'mix'    => __( 'Mix & Match', 'html-landing-page-builder-for-woocommerce' ),
			'bundle' => __( 'Cozy Bundle', 'html-landing-page-builder-for-woocommerce' ),
		);
		return isset( $labels[ $mode ] ) ? $labels[ $mode ] : ( $mode ? $mode : __( 'Unknown / legacy', 'html-landing-page-builder-for-woocommerce' ) );
	}

	private static function status_label( $status ) {
		$statuses = self::get_status_options();
		return isset( $statuses[ $status ] ) ? $statuses[ $status ] : $status;
	}
