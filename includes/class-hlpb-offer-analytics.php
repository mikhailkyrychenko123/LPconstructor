<?php
/**
 * Admin analytics and CSV export for landing-page offer orders.
 *
 * @package HTMLLandingPageBuilderForWooCommerce
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

final class HLPB_Offer_Analytics {
	const PAGE_SLUG       = 'hlpb-offer-analytics';
	const EXPORT_ACTION   = 'hlpb_export_offer_analytics';
	const ORDERS_PER_PAGE = 100;
	const DETAIL_LIMIT    = 100;

	/** Cache WooCommerce coupon metadata during one admin request. */
	private static $coupon_cache = array();

	/** Register the offer analytics screen and CSV action. */
	public static function init() {
		add_action( 'admin_menu', array( __CLASS__, 'register_menu' ) );
		add_action( 'admin_post_' . self::EXPORT_ACTION, array( __CLASS__, 'export_csv' ) );
	}

	/** Add analytics below the plugin's Landing Pages menu. */
	public static function register_menu() {
		add_submenu_page(
			'edit.php?post_type=' . HLPB_Landing_Builder::POST_TYPE,
			__( 'Offer Analytics', 'html-landing-page-builder-for-woocommerce' ),
			__( 'Offer Analytics', 'html-landing-page-builder-for-woocommerce' ),
			'manage_woocommerce',
			self::PAGE_SLUG,
			array( __CLASS__, 'render_page' )
		);
	}

	/** Render coupon, product, and order-line reports for the selected period. */
	public static function render_page() {
		if ( ! current_user_can( 'manage_woocommerce' ) ) {
			return;
		}

		echo '<div class="wrap"><h1>' . esc_html__( 'Offer Analytics', 'html-landing-page-builder-for-woocommerce' ) . '</h1>';
		echo '<p>' . esc_html__( 'Sales and coupon usage generated by this plugin’s landing-page offers. Product revenue is shown excluding tax and after refunds; coupon discounts are shown separately.', 'html-landing-page-builder-for-woocommerce' ) . '</p>';

		if ( ! function_exists( 'wc_get_orders' ) || ! class_exists( 'WC_Order' ) ) {
			echo '<div class="notice notice-warning"><p>' . esc_html__( 'WooCommerce must be active to view offer analytics.', 'html-landing-page-builder-for-woocommerce' ) . '</p></div></div>';
			return;
		}

		$filters  = self::get_filters( $_GET ); // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only report filters.
		$report   = self::build_report( $filters );
		$statuses = self::get_status_options();
		$landings = self::get_landing_options();
		$coupons  = self::get_coupon_options();
		$products = self::get_product_options( $filters['product_id'] );

		self::render_filter_form( $filters, $statuses, $landings, $coupons, $products );
		self::render_summary( $report );
		self::render_coupon_table( $report['coupons'] );
		self::render_product_table( $report['products'] );
		self::render_detail_table( $report['details'], $report['detail_count'] );
		self::render_export_form( $filters );
		echo '</div>';
	}

	/** Download all matching coupon and product sale rows as a UTF-8 CSV. */
	public static function export_csv() {
		if ( ! current_user_can( 'manage_woocommerce' ) ) {
			wp_die( esc_html__( 'You are not allowed to export offer analytics.', 'html-landing-page-builder-for-woocommerce' ) );
		}
		check_admin_referer( self::EXPORT_ACTION );
		if ( ! function_exists( 'wc_get_orders' ) ) {
			wp_die( esc_html__( 'WooCommerce must be active to export offer analytics.', 'html-landing-page-builder-for-woocommerce' ) );
		}

		$filters  = self::get_filters( $_POST ); // phpcs:ignore WordPress.Security.NonceVerification.Missing -- Verified above with a nonce.
		$filename = 'landing-offer-analytics-' . $filters['from'] . '-to-' . $filters['to'] . '.csv';
		nocache_headers();
		header( 'Content-Type: text/csv; charset=utf-8' );
		header( 'Content-Disposition: attachment; filename="' . $filename . '"' );
		$output = fopen( 'php://output', 'w' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_read_fopen -- Stream the requested CSV download.
		if ( false === $output ) {
			exit;
		}
		fwrite( $output, "\xEF\xBB\xBF" ); // UTF-8 BOM for spreadsheet applications.
		$headers = array(
			'record_type', 'order_id', 'order_date', 'order_status', 'landing_page_id', 'landing_page',
			'offer_mode', 'campaign_name', 'coupon_code', 'bundle_id', 'product_id', 'variation_id',
			'product_name', 'sku', 'variation', 'quantity', 'refunded_quantity', 'gross_subtotal_ex_tax',
			'discounted_total_ex_tax', 'line_discount_ex_tax', 'refunded_amount_ex_tax', 'net_sales_ex_tax',
			'line_tax', 'coupon_discount_ex_tax', 'coupon_discount_tax', 'currency', 'is_gift', 'is_addon',
		);
		self::write_csv_row( $output, $headers );

		$page = 1;
		do {
			$result = self::query_order_page( $filters, $page );
			foreach ( $result['orders'] as $order ) {
				$rows        = self::get_filtered_order_rows( $order, $filters );
				$coupon_rows = $rows['coupons'];
				$item_rows   = $rows['items'];

				foreach ( $coupon_rows as $row ) {
					self::write_csv_row(
						$output,
						array(
							'coupon_usage', $row['order_id'], $row['order_date'], $row['order_status'], $row['landing_id'], $row['landing_title'],
							$row['mode'], $row['campaign_name'], $row['code'], '', '', '', '', '', '', '', '', '', '', '', '', '', '',
							$row['discount'], $row['discount_tax'], $row['currency'], '', '',
						)
					);
				}

				foreach ( $item_rows as $row ) {
					self::write_csv_row(
						$output,
						array(
							'product_sale', $row['order_id'], $row['order_date'], $row['order_status'], $row['landing_id'], $row['landing_title'],
							$row['mode'], $row['campaign_name'], $row['coupon_code'], $row['bundle_id'], $row['product_id'], $row['variation_id'],
							$row['product_name'], $row['sku'], $row['variation'], $row['quantity'], $row['refunded_quantity'], $row['subtotal'],
							$row['total'], $row['discount'], $row['refund'], $row['net_sales'], $row['tax'], '', '', $row['currency'],
							$row['is_gift'] ? 1 : 0, $row['is_addon'] ? 1 : 0,
						)
					);
				}
			}
			++$page;
		} while ( $page <= $result['max_pages'] );

		fclose( $output ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_read_fclose -- Close the CSV output stream.
		exit;
	}

	/** Build report totals and grouped views while paging through WooCommerce orders. */
	private static function build_report( $filters ) {
		$report = array(
			'order_ids'    => array(),
			'currencies'   => array(),
			'coupons'      => array(),
			'products'     => array(),
			'details'      => array(),
			'detail_count' => 0,
		);
		$page = 1;
		do {
			$result = self::query_order_page( $filters, $page );
			foreach ( $result['orders'] as $order ) {
				$rows        = self::get_filtered_order_rows( $order, $filters );
				$coupon_rows = $rows['coupons'];
				$item_rows   = $rows['items'];
				if ( ! $coupon_rows && ! $item_rows ) {
					continue;
				}

				$order_id = absint( $order->get_id() );
				$report['order_ids'][ $order_id ] = true;
				foreach ( $coupon_rows as $row ) {
					$key = implode( '|', array( $row['coupon_id'], strtolower( $row['code'] ), $row['currency'] ) );
					if ( ! isset( $report['coupons'][ $key ] ) ) {
						$report['coupons'][ $key ] = array_merge( $row, array( 'orders' => array(), 'uses' => 0, 'discount_total' => 0 ) );
					}
					$report['coupons'][ $key ]['orders'][ $order_id ] = true;
					++$report['coupons'][ $key ]['uses'];
					$report['coupons'][ $key ]['discount_total'] += $row['discount'];
					$report['currencies'][ $row['currency'] ]['coupon_discount'] = ( $report['currencies'][ $row['currency'] ]['coupon_discount'] ?? 0 ) + $row['discount'];
				}

				foreach ( $item_rows as $row ) {
					$key = implode( '|', array( $row['product_id'], $row['variation_id'], $row['landing_id'], $row['mode'], $row['coupon_id'], strtolower( $row['coupon_code'] ), $row['currency'], (int) $row['is_gift'], (int) $row['is_addon'] ) );
					if ( ! isset( $report['products'][ $key ] ) ) {
						$report['products'][ $key ] = array_merge( $row, array( 'orders' => array(), 'lines' => 0, 'quantity_total' => 0, 'refunded_quantity_total' => 0, 'subtotal_total' => 0, 'total_total' => 0, 'discount_total' => 0, 'refund_total' => 0, 'net_sales_total' => 0 ) );
					}
					$group =& $report['products'][ $key ];
					$group['orders'][ $order_id ] = true;
					++$group['lines'];
					$group['quantity_total'] += $row['quantity'];
					$group['refunded_quantity_total'] += $row['refunded_quantity'];
					$group['subtotal_total'] += $row['subtotal'];
					$group['total_total'] += $row['total'];
					$group['discount_total'] += $row['discount'];
					$group['refund_total'] += $row['refund'];
					$group['net_sales_total'] += $row['net_sales'];
					$currency = $row['currency'];
					$report['currencies'][ $currency ]['gross'] = ( $report['currencies'][ $currency ]['gross'] ?? 0 ) + $row['subtotal'];
					$report['currencies'][ $currency ]['discount'] = ( $report['currencies'][ $currency ]['discount'] ?? 0 ) + $row['discount'];
					$report['currencies'][ $currency ]['refund'] = ( $report['currencies'][ $currency ]['refund'] ?? 0 ) + $row['refund'];
					$report['currencies'][ $currency ]['net_sales'] = ( $report['currencies'][ $currency ]['net_sales'] ?? 0 ) + $row['net_sales'];
					unset( $group );
					++$report['detail_count'];
					if ( count( $report['details'] ) < self::DETAIL_LIMIT ) {
						$report['details'][] = $row;
					}
				}
			}
			++$page;
		} while ( $page <= $result['max_pages'] );

		foreach ( $report['coupons'] as &$coupon ) {
			$coupon['order_count'] = count( $coupon['orders'] );
			unset( $coupon['orders'] );
		}
		unset( $coupon );
		foreach ( $report['products'] as &$product ) {
			$product['order_count'] = count( $product['orders'] );
			unset( $product['orders'] );
		}
		unset( $product );
		usort( $report['coupons'], static function ( $left, $right ) { return $right['discount_total'] <=> $left['discount_total']; } );
		usort( $report['products'], static function ( $left, $right ) { return $right['net_sales_total'] <=> $left['net_sales_total']; } );
		return $report;
	}

	/** Query one page of orders without relying on post-table storage. */
	private static function query_order_page( $filters, $page ) {
		$statuses = array_map( static function ( $status ) { return 'wc-' . $status; }, $filters['statuses'] );
		$query = wc_get_orders(
			array(
				'type'         => 'shop_order',
				'status'       => $statuses,
				'date_created' => $filters['from'] . '...' . $filters['to'],
				'limit'        => self::ORDERS_PER_PAGE,
				'page'         => absint( $page ),
				'paginate'     => true,
				'orderby'      => 'date',
				'order'        => 'DESC',
				'return'       => 'objects',
			)
		);
		if ( is_object( $query ) && isset( $query->orders ) ) {
			return array( 'orders' => is_array( $query->orders ) ? $query->orders : array(), 'max_pages' => max( 1, absint( $query->max_num_pages ?? 1 ) ) );
		}
		$orders = is_array( $query ) ? $query : array();
		return array( 'orders' => $orders, 'max_pages' => $orders ? 1 : 0 );
	}

	/** Apply shared report filters and keep coupon rows tied to the selected product. */
	private static function get_filtered_order_rows( $order, $filters ) {
		$all_coupons = self::get_order_coupon_rows( $order );
		$all_items   = self::get_order_offer_item_rows( $order, $all_coupons );
		$items       = self::filter_item_rows( $all_items, $filters );
		$coupons     = self::filter_coupon_rows( $all_coupons, $filters );

		if ( $filters['product_id'] ) {
			$related_ids   = array();
			$related_codes = array();
			foreach ( $items as $item ) {
				if ( $item['coupon_id'] ) {
					$related_ids[] = absint( $item['coupon_id'] );
				} elseif ( $item['coupon_code'] ) {
					$related_codes[] = strtolower( $item['coupon_code'] );
				}
			}
			$coupons = array_values(
				array_filter(
					$coupons,
					static function ( $coupon ) use ( $related_ids, $related_codes ) {
						return ( $coupon['coupon_id'] && in_array( absint( $coupon['coupon_id'] ), $related_ids, true ) ) || in_array( strtolower( $coupon['code'] ), $related_codes, true );
					}
				)
			);
		}

		return array( 'coupons' => $coupons, 'items' => $items );
	}

	/** Return only plugin-owned coupon use rows attached to this order. */
	private static function get_order_coupon_rows( $order ) {
		$rows = array();
		$date = $order->get_date_created();
		foreach ( $order->get_items( 'coupon' ) as $coupon_item ) {
			$code = sanitize_text_field( $coupon_item->get_code() );
			$coupon_id = function_exists( 'wc_get_coupon_id_by_code' ) ? absint( wc_get_coupon_id_by_code( $code ) ) : 0;
			$data = self::coupon_data_from_order_lines( $order, $coupon_id, $code );
			if ( ! $data ) {
				$data = self::get_coupon_data( $coupon_id, $code );
			}
			if ( ! $data ) {
				continue;
			}
			$rows[] = array(
				'order_id'      => absint( $order->get_id() ),
				'order_date'    => $date ? wc_format_datetime( $date, 'Y-m-d H:i:s' ) : '',
				'order_status'  => $order->get_status(),
				'coupon_id'     => absint( $data['coupon_id'] ),
				'code'          => $code,
				'campaign_name' => $data['campaign_name'],
				'mode'          => $data['mode'],
				'landing_id'    => absint( $data['landing_id'] ),
				'landing_title' => $data['landing_title'],
				'discount'      => abs( (float) $coupon_item->get_discount() ),
				'discount_tax'  => abs( (float) $coupon_item->get_discount_tax() ),
				'currency'      => sanitize_text_field( $order->get_currency() ),
			);
		}
		return $rows;
	}

	/** Read offer line items saved by the checkout integration, including older records. */
	private static function get_order_offer_item_rows( $order, $coupon_rows ) {
		$rows = array();
		$date = $order->get_date_created();
		foreach ( $order->get_items( 'line_item' ) as $item_id => $item ) {
			$landing_id = absint( $item->get_meta( '_hlpb_landing_id', true ) );
			$bundle_key = sanitize_text_field( $item->get_meta( '_hlpb_bundle_key', true ) );
			if ( ! $landing_id || '' === $bundle_key ) {
				continue;
			}

			$coupon_id = absint( $item->get_meta( '_hlpb_coupon_id', true ) );
			$coupon_code = sanitize_text_field( $item->get_meta( '_hlpb_coupon_code', true ) );
			$matched_coupon = false;
			foreach ( $coupon_rows as $coupon_row ) {
				if ( ( $coupon_id && $coupon_row['coupon_id'] === $coupon_id ) || ( ! $coupon_id && $coupon_code && strtolower( $coupon_row['code'] ) === strtolower( $coupon_code ) ) ) {
					$matched_coupon = $coupon_row;
					break;
				}
			}
			if ( ! $matched_coupon && ! $coupon_id && ! $coupon_code ) {
				$matching = array_values( array_filter( $coupon_rows, static function ( $row ) use ( $landing_id ) { return absint( $row['landing_id'] ) === $landing_id; } ) );
				if ( 1 === count( $matching ) ) {
					$matched_coupon = $matching[0];
					$coupon_id = absint( $matched_coupon['coupon_id'] );
					$coupon_code = $matched_coupon['code'];
				}
			}
			$coupon_data = $coupon_id ? self::get_coupon_data( $coupon_id, $coupon_code ) : false;
			$mode = sanitize_key( $item->get_meta( '_hlpb_offer_mode', true ) );
			if ( '' === $mode && $matched_coupon ) {
				$mode = $matched_coupon['mode'];
			}
			if ( '' === $mode && $coupon_data ) {
				$mode = $coupon_data['mode'];
			}
			$campaign_name = sanitize_text_field( $item->get_meta( '_hlpb_campaign_name', true ) );
			if ( '' === $campaign_name && $matched_coupon ) {
				$campaign_name = $matched_coupon['campaign_name'];
			}
			if ( '' === $campaign_name && $coupon_data ) {
				$campaign_name = $coupon_data['campaign_name'];
			}
			if ( '' === $campaign_name ) {
				$campaign_name = sanitize_text_field( $item->get_meta( __( 'Landing offer', 'html-landing-page-builder-for-woocommerce' ), true ) );
			}

			$product = $item->get_product();
			$parent_product = wc_get_product( $item->get_product_id() );
			$variation_id = absint( $item->get_variation_id() );
			$quantity = absint( $item->get_quantity() );
			$subtotal = (float) $item->get_subtotal();
			$total = (float) $item->get_total();
			$refund = abs( (float) $order->get_total_refunded_for_item( $item_id ) );
			$refunded_quantity = absint( $order->get_qty_refunded_for_item( $item_id ) );
			$product_name = sanitize_text_field( $item->get_name() );
			$sku = $product && $product->get_sku() ? $product->get_sku() : ( $parent_product ? $parent_product->get_sku() : '' );
			$landing_title = get_the_title( $landing_id );
			$variation = self::get_variation_label( $item );
			$rows[] = array(
				'order_id'           => absint( $order->get_id() ),
				'order_date'         => $date ? wc_format_datetime( $date, 'Y-m-d H:i:s' ) : '',
				'order_status'       => $order->get_status(),
				'landing_id'         => $landing_id,
				'landing_title'      => $landing_title ? sanitize_text_field( $landing_title ) : sprintf( __( 'Landing page #%d', 'html-landing-page-builder-for-woocommerce' ), $landing_id ),
				'mode'               => $mode,
				'campaign_name'      => $campaign_name,
				'coupon_id'          => $coupon_id,
				'coupon_code'        => $coupon_code,
				'bundle_id'          => strtoupper( substr( preg_replace( '/[^a-f0-9]/i', '', $bundle_key ), 0, 8 ) ),
				'product_id'         => absint( $item->get_product_id() ),
				'variation_id'       => $variation_id,
				'product_name'       => $product_name,
				'sku'                => sanitize_text_field( $sku ),
				'variation'          => $variation,
				'quantity'           => $quantity,
				'refunded_quantity'  => $refunded_quantity,
				'subtotal'           => $subtotal,
				'total'              => $total,
				'discount'           => $subtotal - $total,
				'refund'             => $refund,
				'net_sales'          => $total - $refund,
				'tax'                => (float) $item->get_total_tax(),
				'is_gift'            => '1' === (string) $item->get_meta( '_hlpb_is_gift', true ) || 1 === absint( $item->get_meta( '_hlpb_is_gift', true ) ),
				'is_addon'           => '1' === (string) $item->get_meta( '_hlpb_is_addon', true ) || 1 === absint( $item->get_meta( '_hlpb_is_addon', true ) ),
				'currency'           => sanitize_text_field( $order->get_currency() ),
			);
		}
		return $rows;
	}

	/** Resolve an offer coupon to the landing page and mode stored on its WooCommerce coupon. */
	private static function get_coupon_data( $coupon_id, $code = '' ) {
		$coupon_id = absint( $coupon_id );
		if ( $coupon_id && array_key_exists( $coupon_id, self::$coupon_cache ) ) {
			return self::$coupon_cache[ $coupon_id ];
		}
		if ( ! $coupon_id || 'shop_coupon' !== get_post_type( $coupon_id ) || ! class_exists( 'WC_Coupon' ) ) {
			return false;
		}
		$coupon = new WC_Coupon( $coupon_id );
		if ( ! $coupon->get_id() || 'yes' !== $coupon->get_meta( HLPB_Cart_Section::COUPON_FLAG_META, true ) ) {
			self::$coupon_cache[ $coupon_id ] = false;
			return false;
		}
		$landing_id = absint( $coupon->get_meta( HLPB_Cart_Section::COUPON_LANDING_META, true ) );
		$campaign = sanitize_text_field( $coupon->get_meta( '_hlpb_campaign_name', true ) );
		if ( '' === $campaign ) {
			$campaign = sanitize_text_field( $coupon->get_code() );
		}
		$landing_title = $landing_id ? get_the_title( $landing_id ) : '';
		$data = array(
			'coupon_id'     => $coupon_id,
			'code'          => sanitize_text_field( $coupon->get_code() ? $coupon->get_code() : $code ),
			'campaign_name' => $campaign,
			'mode'          => sanitize_key( $coupon->get_meta( '_hlpb_offer_mode', true ) ),
			'landing_id'    => $landing_id,
			'landing_title' => $landing_title ? sanitize_text_field( $landing_title ) : ( $landing_id ? sprintf( __( 'Landing page #%d', 'html-landing-page-builder-for-woocommerce' ), $landing_id ) : '' ),
		);
		self::$coupon_cache[ $coupon_id ] = $data;
		return $data;
	}

	/** Recognize plugin coupon uses even if the coupon post was later removed. */
	private static function coupon_data_from_order_lines( $order, $coupon_id, $code ) {
		foreach ( $order->get_items( 'line_item' ) as $item ) {
			$item_coupon_id = absint( $item->get_meta( '_hlpb_coupon_id', true ) );
			$item_coupon_code = sanitize_text_field( $item->get_meta( '_hlpb_coupon_code', true ) );
			$matches = ( $coupon_id && $item_coupon_id === $coupon_id ) || ( $code && $item_coupon_code && strtolower( $item_coupon_code ) === strtolower( $code ) );
			if ( ! $matches ) {
				continue;
			}
			$landing_id = absint( $item->get_meta( '_hlpb_landing_id', true ) );
			if ( ! $landing_id ) {
				continue;
			}
			$landing_title = get_the_title( $landing_id );
			return array(
				'coupon_id'     => $item_coupon_id,
