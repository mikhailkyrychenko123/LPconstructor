	/** Sanitize date, status, landing, and coupon filters from GET or POST. */
	private static function get_filters( $source ) {
		$source = is_array( $source ) ? $source : array();
		$today = wp_date( 'Y-m-d' );
		$default_from = wp_date( 'Y-m-d', time() - ( 29 * DAY_IN_SECONDS ) );
		$from = self::valid_date( isset( $source['from'] ) ? $source['from'] : '', $default_from );
		$to = self::valid_date( isset( $source['to'] ) ? $source['to'] : '', $today );
		if ( $from > $to ) {
			$temp = $from;
			$from = $to;
			$to = $temp;
		}
		$valid_statuses = array_keys( self::get_status_options() );
		$statuses = isset( $source['statuses'] ) && is_array( $source['statuses'] ) ? array_map( 'sanitize_key', array_filter( wp_unslash( $source['statuses'] ), 'is_scalar' ) ) : array( 'processing', 'completed', 'on-hold', 'refunded' );
		$statuses = array_values( array_unique( array_intersect( $statuses, $valid_statuses ) ) );
		if ( ! $statuses ) {
			$statuses = array( 'processing', 'completed', 'on-hold', 'refunded' );
		}
		$mode = isset( $source['mode'] ) && is_scalar( $source['mode'] ) ? sanitize_key( $source['mode'] ) : '';
		return array(
			'from'       => $from,
			'to'         => $to,
			'statuses'   => $statuses,
			'landing_id' => absint( $source['landing_id'] ?? 0 ),
			'coupon_id'  => absint( $source['coupon_id'] ?? 0 ),
			'product_id' => absint( $source['product_id'] ?? 0 ),
			'mode'       => in_array( $mode, array( 'buy', 'mix', 'bundle' ), true ) ? $mode : '',
		);
	}

	/** Accept exact calendar dates only. */
	private static function valid_date( $value, $fallback ) {
		$value = is_scalar( $value ) ? sanitize_text_field( (string) $value ) : '';
		$date = DateTime::createFromFormat( '!Y-m-d', $value );
		return $date && $date->format( 'Y-m-d' ) === $value ? $value : $fallback;
	}

	/** List order statuses available to the WooCommerce report filter. */
